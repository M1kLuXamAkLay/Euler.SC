const LANGS = ['ru', 'en', 'zh', 'es', 'fr', 'bn', 'pt'];

/** Active language. Switched through I18n.set(). */
let currentLang = 'ru';

const I18n = {
  langs: LANGS,

  /** Locale: saved choice, then the system language, then Russian. */
  detect(saved) {
    if (saved && I18N[saved]) return saved;
    const nav = (navigator.language || 'ru').slice(0, 2).toLowerCase();
    return I18N[nav] ? nav : 'ru';
  },

  set(lang) {
    if (!I18N[lang]) lang = 'ru';
    currentLang = lang;
    document.documentElement.lang = lang;
    this.apply();
  },

  get() {
    return currentLang;
  },

  /** Translate by key. An unknown key is returned as is, which shows up at once. */
  t(key) {
    const table = I18N[currentLang] || I18N.ru;
    return table[key] ?? I18N.ru[key] ?? key;
  },

  /**
   * Applies every translation the markup declares:
   *   data-i18n         -> textContent
   *   data-i18n-ph      -> placeholder
   *   data-i18n-title   -> title (tooltip)
   */
  apply() {
    for (const el of document.querySelectorAll('[data-i18n]')) {
      el.textContent = this.t(el.dataset.i18n);
    }
    for (const el of document.querySelectorAll('[data-i18n-ph]')) {
      el.placeholder = this.t(el.dataset.i18nPh);
    }
    for (const el of document.querySelectorAll('[data-i18n-title]')) {
      el.title = this.t(el.dataset.i18nTitle);
    }
    document.title = this.t('app.title');
  },
};

/**
 * Short global helpers. ``t('key')`` appears hundreds of times in app.js, and
 * writing ``I18n.t('key')`` each time would bury the code.
 */
function t(key) {
  return I18n.t(key);
}


/**
 * Resolve an engine key into a localised sentence.
 *
 * @param {string} raw key such as ``ExprError.bad_name:foo`` or plain text
 * @param {string[]} args positional replacements for ``{0}``, ``{1}``
 * @returns {string} localised message, or the input when no translation exists
 */
function message(raw, args = []) {
  if (typeof raw !== 'string' || !raw) return '';

  const [key, ...inline] = raw.split(':');
  const lang = I18n.get();

  // Two tables hold text: MESSAGES for engine errors (with {0} placeholders)
  // and I18N for interface strings. Look in both, so a section heading and an
  // error key resolve the same way.
  let text = null;
  if (MESSAGES[key]) {
    text = MESSAGES[key][lang] || MESSAGES[key].ru || null;
  }
  if (text === null && I18N[lang] && I18N[lang][key] !== undefined) {
    text = I18N[lang][key];
  }
  if (text === null && I18N.ru && I18N.ru[key] !== undefined) {
    text = I18N.ru[key];
  }
  if (text === null) return raw;

  const values = inline.concat(args);
  values.forEach((value, index) => {
    text = text.split(`{${index}}`).join(String(value));
  });
  return text;
}

if (typeof window !== 'undefined') {
  window.I18N = I18N;
  window.I18n = I18n;
  window.t = t;
  window.message = message;
}

if (typeof module !== 'undefined') module.exports = { I18N, I18n, LANGS, t };

