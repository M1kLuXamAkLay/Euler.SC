#!/usr/bin/env python3
"""Derive every version stamp in the project from one place: ``euler/__init__.py``.

The version used to be written by hand in four files — the package, the Windows
version resource, the NSIS script and the docs — and they drifted. They drifted
in exactly the way that matters for an installer: ``version_info.txt`` still said
``5,1,0,0`` while the package said ``5.2.1``, so Windows Explorer and the
"Programs and features" list disagreed with the application about what was
installed. An upgrade check built on a stale number would refuse to upgrade.

Run before every build; ``build/build.bat``, ``build/build.sh`` and the release
workflow all call it. Writes:

    build/version.nsh        !define APP_VERSION + numeric parts, for NSIS
    build/version_info.txt   Windows VS_VERSIONINFO resource

Exit code is non-zero on a malformed version, so a build cannot ship a version
string a comparison cannot parse.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INIT = ROOT / "euler" / "__init__.py"
NSH = ROOT / "build" / "version.nsh"
VERSION_INFO = ROOT / "build" / "version_info.txt"

# MAJOR.MINOR.PATCH, optionally with a pre-release suffix (-rc1, -beta.2).
_SEMVER = re.compile(r"^(\d+)\.(\d+)\.(\d+)(?:[-+]?([0-9A-Za-z.\-]+))?$")


def read_version() -> str:
    """The version declared by the package, as a string."""
    text = INIT.read_text(encoding="utf-8")
    match = re.search(r'^__version__\s*=\s*"([^"]+)"', text, re.MULTILINE)
    if not match:
        raise SystemExit(f"sync_version: no __version__ in {INIT}")
    return match.group(1)


def parse(version: str) -> tuple[int, int, int, str]:
    """Split a version into its three numbers and its suffix."""
    match = _SEMVER.match(version)
    if not match:
        raise SystemExit(f"sync_version: {version!r} is not MAJOR.MINOR.PATCH")
    major, minor, patch, suffix = match.groups()
    return int(major), int(minor), int(patch), suffix or ""


def write_nsh(version: str, parts: tuple[int, int, int, str]) -> None:
    """The NSIS fragment: one definition per number, so the script never parses."""
    major, minor, patch, _ = parts
    body = f"""\
; Generated by build/sync_version.py from euler/__init__.py. Do not edit.
;
; The installer reads the version from here and never hard-codes it. A build that
; forgets to regenerate this file is caught by tests/test_installer_meta.py.
!define APP_VERSION       "{version}"
!define APP_VERSION_MAJOR {major}
!define APP_VERSION_MINOR {minor}
!define APP_VERSION_PATCH {patch}
"""
    NSH.write_text(body, encoding="utf-8")


def write_version_info(version: str, parts: tuple[int, int, int, str]) -> None:
    """The Windows resource. ``filevers`` must be a four-number tuple."""
    major, minor, patch, _ = parts
    body = f"""\
# Generated by build/sync_version.py from euler/__init__.py. Do not edit.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=({major}, {minor}, {patch}, 0),
    prodvers=({major}, {minor}, {patch}, 0),
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable(
        '040904B0',
        [StringStruct('CompanyName', 'Euler Project'),
         StringStruct('FileDescription', 'Euler.SC - symbolic calculator'),
         StringStruct('FileVersion', '{version}.0'),
         StringStruct('InternalName', 'EulerSC'),
         StringStruct('LegalCopyright', 'MIT License'),
         StringStruct('OriginalFilename', 'EulerSC.exe'),
         StringStruct('ProductName', 'Euler.SC'),
         StringStruct('ProductVersion', '{version}.0')])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""
    VERSION_INFO.write_text(body, encoding="utf-8")


def main() -> int:
    version = read_version()
    parts = parse(version)
    write_nsh(version, parts)
    write_version_info(version, parts)
    print(f"sync_version: {version}  ->  {NSH.name}, {VERSION_INFO.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
