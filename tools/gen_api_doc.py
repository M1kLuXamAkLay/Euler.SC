"""Generate docs/API.md from the exported Api surface.

The document is derived from code, never edited by hand. tests/test_api_doc.py
regenerates it in memory and fails if the committed file differs, so a new or
changed method cannot ship without its documentation.

Run:  python tools/gen_api_doc.py
"""
from __future__ import annotations

import inspect
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from euler.bridge.api import Api  # noqa: E402

OUTPUT = ROOT / "docs" / "API.md"


def _signature(method) -> str:
    sig = inspect.signature(method)
    parts = []
    for name, param in sig.parameters.items():
        if name == "self":
            continue
        text = name
        if param.annotation is not inspect.Parameter.empty:
            annotation = param.annotation
            label = getattr(annotation, "__name__", None) or str(annotation)
            text += f": {label.replace('typing.', '')}"
        if param.default is not inspect.Parameter.empty:
            text += f" = {param.default!r}"
        parts.append(text)
    return f"({', '.join(parts)})"


def _summary(method) -> str:
    doc = inspect.getdoc(method) or ""
    first = doc.strip().split("\n\n")[0].replace("\n", " ").strip()
    # Double backticks render oddly inside a table cell, and a pipe would end it
    first = first.replace("``", "`").replace("|", "\\|")
    return first or "_No description._"


def render() -> str:
    exported = sorted(Api._exported)
    lines = [
        "# API reference",
        "",
        "<!-- Generated by tools/gen_api_doc.py. Do not edit by hand. -->",
        "",
        "Every method the interface may call. The page sends `POST /api/<name>`",
        "with a JSON object of keyword arguments; the response is the JSON result.",
        "A method that is not listed here cannot be reached, even with a valid token.",
        "",
        "## Calling convention",
        "",
        "```http",
        "POST /api/solve?token=<token>",
        "Content-Type: application/json",
        "",
        '{"expression": "2^10"}',
        "```",
        "",
        "Failures return `{\"ok\": false, \"error\": \"<message key>\"}` with HTTP 200,",
        "except transport errors (`403` bad token or host, `400` malformed body,",
        "`413` body over 8 MiB). Error strings are translation keys such as",
        "`ExprError.bad_name:x`, not prose.",
        "",
        f"## Methods ({len(exported)})",
        "",
        "| Method | Parameters | Purpose |",
        "|---|---|---|",
    ]
    for name in exported:
        method = getattr(Api, name)
        lines.append(f"| `{name}` | `{_signature(method)}` | {_summary(method)} |")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
